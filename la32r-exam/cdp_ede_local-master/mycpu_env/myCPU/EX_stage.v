// 说明：引入各级总线宽度和访存宽度的公共定义。
`include "mycpu_defines.vh"

// 说明：定义执行阶段模块及其对外接口。
module EX_stage(
    // 说明：作为输入端口接收时钟信号。
    input  wire        clk,
    // 说明：作为输入端口接收高电平复位信号。
    input  wire        reset,
    //allowin
    // 说明：作为输入端口接收访存级可接收新结果的标志。
    input  wire        ms_allowin,  //握手信号
    // 说明：作为输出端口送出执行级可接收新指令的标志。
    output wire        es_allowin,  //该阶段是否k可以接收数据
    //from ds stage
    // 说明：作为输入端口接收译码传给执行级的有效位。
    input  wire        ds_to_es_valid,
    // 说明：作为输入端口接收译码传给执行级的控制和数据总线。
    input  wire [`DS_TO_ES_BUS_WD -1 :0] ds_to_es_bus,  //上一级缓冲区
    //to ms stage
    // 说明：作为输出端口送出执行传给访存级的有效位。
    output wire        es_to_ms_valid,  //告知下一级数据是否有效
    // 说明：作为输出端口送出执行传给访存级的结果总线。
    output wire [`ES_TO_MS_BUS_WD -1 :0] es_to_ms_bus  //下一级缓冲区

// 说明：结束模块端口列表或子模块端口连接。
);
    // 说明：声明需要随时钟保存的执行级有效位。
    reg es_valid;
    // 说明：声明需要随时钟保存的执行级保存的译码总线。
    reg [`DS_TO_ES_BUS_WD -1 :0] ds_to_es_bus_r;
    // 说明：声明执行级已完成本拍计算的标志，供本模块连接或计算。
    wire es_ready_go;

    // 说明：执行级 ALU 运算在本拍组合完成，所以本级始终就绪。
    assign es_ready_go    = 1'b1;
    // 说明：本级为空，或已完成且访存级可接收时，允许下一条进入。
    assign es_allowin      = !es_valid || es_ready_go && ms_allowin;
    // 说明：本级持有有效指令时，向访存级发出有效标志。
    assign es_to_ms_valid  = es_valid && es_ready_go;
    // 说明：在时钟上升沿更新本级保存的有效位和数据。
    always @(posedge clk) begin
        // 说明：复位有效时清空本级状态，使旧指令不再有效。
        if (reset) begin
            // 说明：更新执行级有效位，控制该级数据是否被下游采纳。
            es_valid <= 1'b0;
            // 说明：把上一级总线内容暂存为执行级保存的译码总线。
            ds_to_es_bus_r <= 0;
        // 说明：结束当前条件分支或时序代码块。
        end
        // 说明：只有括号里的条件成立，才执行这一分支的状态更新。
        else if (es_allowin) begin
             // 说明：更新执行级有效位，控制该级数据是否被下游采纳。
             es_valid <= ds_to_es_valid;
        // 说明：结束当前条件分支或时序代码块。
        end

        // 说明：仅在上游数据有效且本级可以接收时锁存译码结果。
        if (ds_to_es_valid && es_allowin) begin
            // 说明：把上一级总线内容暂存为执行级保存的译码总线。
            ds_to_es_bus_r <= ds_to_es_bus;
        // 说明：结束当前条件分支或时序代码块。
        end
        // 说明：进入前一个条件不成立时的处理分支。
        else begin
            // 说明：把上一级总线内容暂存为执行级保存的译码总线。
            ds_to_es_bus_r <= 0;
        // 说明：结束当前条件分支或时序代码块。
        end
    // 说明：结束当前条件分支或时序代码块。
    end
    /*assign ds_to_es_bus = {alu_op       ,  //[151:140] 12 bit
                       load_op      ,  //[139]      1 bit
                       src1_is_pc   ,  //[138]      1 bit
                       src2_is_imm  ,  //[137]      1 bit
                       src2_is_4    ,  //[136]      1 bit
                       gr_we        ,  //[135]      1 bit
                       mem_we       ,  //[134]      1 bit
                       dest         ,  //[133:129]  5 bit
                       imm          ,  //[128: 97] 32 bit
                       rj_value     ,  //[ 96: 65] 32 bit   //第一个操作数的值
                       rkd_value    ,  //[ 64: 33] 32 bit   //第二个操作数的值，有可能作为地址
                       ds_pc        ,  //[ 32:  1] 32 bit
                       res_from_mem    //[  0]      1 bit
                      };*/
    // 说明：声明加载结果需要符号扩展的标志，供本模块连接或计算。
    wire load_signed;
    // 说明：声明本次访存的数据宽度编码，供本模块连接或计算。
    wire [1:0] mem_size;
    // 说明：声明ALU 运算选择位，供本模块连接或计算。
    wire [11:0] alu_op;
    // 说明：声明当前指令是加载指令的标志，供本模块连接或计算。
    wire load_op;
    // 说明：声明执行级传递的寄存器写使能，供本模块连接或计算。
    wire ex_gr_we;
    // 说明：声明最终要写的寄存器编号，供本模块连接或计算。
    wire [4:0] dest;
    // 说明：声明ALU 最终输出结果，供本模块连接或计算。
    wire [31:0] alu_result;
    // 说明：声明ALU 第一输入选择 PC 的标志，供本模块连接或计算。
    wire        src1_is_pc;
    // 说明：声明ALU 第二输入选择立即数的标志，供本模块连接或计算。
    wire        src2_is_imm;
    // 说明：声明ALU 第二输入需要常数 4 的标志，供本模块连接或计算。
    wire        src2_is_4;
    // 说明：声明数据内存写使能标志，供本模块连接或计算。
    wire        mem_we;
    // 说明：声明扩展成 32 位的立即数，供本模块连接或计算。
    wire [31:0] imm;
    // 说明：声明经过前递选择的 rj 值，供本模块连接或计算。
    wire [31:0] rj_value;
    // 说明：声明经过前递选择的第二源寄存器值，供本模块连接或计算。
    wire [31:0] rkd_value;
    // 说明：声明当前指令的 PC，供本模块连接或计算。
    wire [31:0] ds_pc;
    // 说明：声明写回数据来自内存的标志，供本模块连接或计算。
    wire        res_from_mem;

    // 说明：开始按译码总线规定的字段顺序拆出控制位和操作数。
    assign {
            // 说明：把加载结果需要符号扩展的标志放入当前总线字段或选择条件。
            load_signed,
            // 说明：把本次访存的数据宽度编码放入当前总线字段或选择条件。
            mem_size,
            // 说明：把ALU 运算选择位放入当前总线字段或选择条件。
            alu_op,
            // 说明：把当前指令是加载指令的标志放入当前总线字段或选择条件。
            load_op,
            // 说明：把ALU 第一输入选择 PC 的标志放入当前总线字段或选择条件。
            src1_is_pc,
            // 说明：把ALU 第二输入选择立即数的标志放入当前总线字段或选择条件。
            src2_is_imm,
            // 说明：把ALU 第二输入需要常数 4 的标志放入当前总线字段或选择条件。
            src2_is_4,
            // 说明：把执行级传递的寄存器写使能放入当前总线字段或选择条件。
            ex_gr_we,
            // 说明：把数据内存写使能标志放入当前总线字段或选择条件。
            mem_we,
            // 说明：把最终要写的寄存器编号放入当前总线字段或选择条件。
            dest,
            // 说明：把扩展成 32 位的立即数放入当前总线字段或选择条件。
            imm,
            // 说明：把经过前递选择的 rj 值放入当前总线字段或选择条件。
            rj_value,
            // 说明：把经过前递选择的第二源寄存器值放入当前总线字段或选择条件。
            rkd_value,
            // 说明：把当前指令的 PC放入当前总线字段或选择条件。
            ds_pc,
            // 说明：最后拆出结果是否来自内存的标志，完成总线解包。
            res_from_mem} = ds_to_es_bus_r;

    // 说明：声明ALU 第一个输入数，供本模块连接或计算。
    wire [31:0] alu_src1;
    // 说明：声明ALU 第二个输入数，供本模块连接或计算。
    wire [31:0] alu_src2;
    // 说明：JIRL、BL、PCADDU12I 使用 PC；其他运算使用 rj。
    assign alu_src1 = src1_is_pc  ? ds_pc[31:0] : rj_value;
    // 说明：立即数指令用 imm；寄存器指令用第二源寄存器值。
    assign alu_src2 = src2_is_imm ? imm : rkd_value;


    // 说明：实例化算术逻辑单元，处理本级的运算。
    alu _alu(
        // 说明：把ALU 运算选择位接到子模块的对应端口。
        .alu_op(alu_op),
        // 说明：把ALU 第一个输入数接到子模块的对应端口。
        .alu_src1(alu_src1),
        // 说明：把ALU 第二个输入数接到子模块的对应端口。
        .alu_src2(alu_src2),
        // 说明：把ALU 最终输出结果接到子模块的对应端口。
        .alu_result(alu_result)
    // 说明：结束模块端口列表或子模块端口连接。
    );


    // 说明：开始打包执行结果和写回、访存控制信息。
    assign es_to_ms_bus = {
                        // 说明：把加载结果需要符号扩展的标志放入当前总线字段或选择条件。
                        load_signed,  //[107]     1 bit   加载的数据是否要进行有符号扩展
                        // 说明：把本次访存的数据宽度编码放入当前总线字段或选择条件。
                        mem_size,    //[106:105] 2 bit   内存写入/读取的数据大小    
                        // 说明：把执行级传递的寄存器写使能放入当前总线字段或选择条件。
                        ex_gr_we     ,  //[104]     1 bit   写寄存器使能
                        // 说明：把最终要写的寄存器编号放入当前总线字段或选择条件。
                        dest         ,  //[103: 99] 5 bit   写寄存器地址
                            
                        // 说明：把当前指令是加载指令的标志放入当前总线字段或选择条件。
                        load_op      ,  //[ 98]     1 bit   load指令
                        // 说明：把写回数据来自内存的标志放入当前总线字段或选择条件。
                        res_from_mem ,  //[ 97]     1 bit   结果是否来自内存

                        // 说明：把数据内存写使能标志放入当前总线字段或选择条件。
                        mem_we       ,  //[ 96]     1 bit   写内存使能
                        // 说明：把经过前递选择的第二源寄存器值放入当前总线字段或选择条件。
                        rkd_value    ,  //[ 95: 64] 32 bit  写内存数据
                        // 说明：把ALU 最终输出结果放入当前总线字段或选择条件。
                        alu_result   ,  //[ 63: 32] 32 bit  alu计算结果
                        // 说明：把当前指令的 PC放入当前总线字段或选择条件。
                        ds_pc           //[ 31:  0] 32 bit  当前指令的pc,用于debug
                        // 说明：完成执行到访存级的数据总线拼接。
                        };
// 说明：结束执行阶段模块定义。
endmodule